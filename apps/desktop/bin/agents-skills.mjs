export const SKILLS_USAGE = `Usage: bmn skills check [--json]                    One state per app and per skill; exit 0 only when every supported app has its skills
       bmn skills install [app…] [--plan] [--yes]   Link or copy each app's skills, and remove what an app may no longer have, as one transaction
       bmn skills test <app> [--json]               Owner-run: find where the app reads skills, then whether it lists a skill placed there (no prompt)
       bmn skills test <app> --prompt [--json]      Owner-run: one prompt to that app's provider, to see whether the app hands a test skill to its model

Apps: ${HARNESSES.join(', ')}. The skills come from ~/.claude/skills unless the approved team names another folder.
Undo an install with: bmn rules restore --transaction <id>`

async function installedVersions(environment = process.env) {
  const { harnessVersion } = await import('./agents-check.mjs')
  return Object.fromEntries(HARNESSES.map((harness) => [harness, harnessVersion(SKILL_APPS[harness].command, environment)]))
}

function checkLines(result) {
  const lines = [result.source.readable ? `Skills folder: ${result.source.path} (${result.skills.length} skill${result.skills.length === 1 ? '' : 's'})` : `Skills folder: ${result.source.path}: ${result.source.detail}`]
  if (result.marked_missing.length > 0) lines.push(`Marked in the team file but not in the folder: ${result.marked_missing.join(', ')}`)
  for (const app of result.apps) {
    const name = `${APP_NAMES[app.harness]}${app.version ? ` ${app.version}` : ''}`
    if (!app.supported) {
      lines.push(`${name}: skills not supported yet (${app.reason})`)
      continue
    }
    const where = app.reads_source ? 'reads the skills folder itself' : `${app.location} (${app.format === 'link' ? 'links' : 'copies'})`
    lines.push(`${name}: ${appStateWord(app, result.source.readable)} - ${where}; ${app.kind === 'full' ? 'every skill it may have' : 'public skills only'}`)
    const groups = new Map()
    for (const skill of app.skills) groups.set(skill.state, [...(groups.get(skill.state) ?? []), skill.name])
    for (const [state, names] of groups) lines.push(SETTLED_STATES.includes(state) ? `  ${state}: ${names.length}` : `  ${state}: ${names.join(', ')}`)
  }
  return lines.join('\n')
}

export async function runSkillsCommand(argv) {
  const { AgentsUsageError, EXIT, failWith, out, readOptions, usage } = await import('./agents-cli.mjs')
  const [action, ...rest] = argv
  if (action === undefined || action === '--help' || action === '-h' || action === 'help') {
    out(SKILLS_USAGE)
    return action === undefined ? 2 : 0
  }
  let asJson = false
  try {
    if (action === 'check') {
      const { options, positionals } = readOptions(rest, { flags: ['json'] })
      asJson = options.json === true
      if (positionals.length > 0) return usage('skills check takes no arguments')
      const result = checkSkills({ versions: await installedVersions() })
      const code = checkExit(result)
      out(asJson ? JSON.stringify({ ok: code === 0, ...result }, null, 2) : checkLines(result))
      return code
    }
    if (action === 'install') {
      const { options, positionals } = readOptions(rest, { flags: ['json', 'plan', 'yes'], values: ['expect-plan'] })
      asJson = options.json === true
      const unknown = positionals.filter((name) => !HARNESSES.includes(name))
      if (unknown.length > 0) return usage(`skills install expects apps from ${HARNESSES.join(', ')}, not ${unknown.join(', ')}`)
      const versions = await installedVersions()
      if (options.plan) {
        const planned = await planSkillsInstall(positionals, { versions })
        out(asJson ? JSON.stringify(skillsPlanView(planned), null, 2) : planned.code !== 'OK' ? `${planned.code}: ${planned.message}` : planDetails(planned) || 'Every app already has its skills.')
        return planned.code === 'OK' ? 0 : EXIT.refusal
      }
      const result = await installSkills(positionals, { yes: options.yes === true, asJson, versions, expectedPlanHash: options['expect-plan'] })
      if (asJson) out(JSON.stringify(result, null, 2))
      else if (result.code === 'OK') {
        out([result.message ?? `Changed ${result.written.length} entr${result.written.length === 1 ? 'y' : 'ies'} (transaction ${result.transaction}).`,
          ...result.exposed.map((entry) => `still exposed: ${entry.harness} ${entry.skill} - ${entry.fix}`),
          ...(result.transaction ? ['Sessions started before this keep the skills they had.'] : [])].join('\n'))
      } else if (result.code !== 'NOT_CONFIRMED') process.stderr.write(`bmn: ${result.code}: ${result.message}\n`)
      if (result.code === 'REVISION_CONFLICT') return EXIT.REVISION_CONFLICT
      if (result.code === 'NOT_CONFIRMED') return asJson ? 2 : 1
      if (result.code !== 'OK') return result.code === 'INSTALL_FAILED' ? 1 : EXIT.refusal
      // An install never reports success while a skill is exposed.
      return result.exposed.length > 0 ? 1 : 0
    }
    if (action === 'test') {
      const { options, positionals } = readOptions(rest, { flags: ['json', 'prompt'] })
      asJson = options.json === true
      if (positionals.length !== 1 || !HARNESSES.includes(positionals[0])) return usage(`skills test expects one app: ${HARNESSES.join(', ')}`)
      const result = options.prompt === true ? await testSkillsLoading(positionals[0]) : await testSkills(positionals[0])
      out(asJson ? JSON.stringify(result, null, 2) : `${result.harness}: ${result.outcome} - ${result.detail}${result.version ? ` (${result.version})` : ''}`)
      return result.outcome === 'pass' ? 0 : 1
    }
    return usage(`skills expects check, install or test, not ${action}`)
  } catch (error) {
    if (error instanceof AgentsUsageError) return usage(error.message)
    if (error instanceof SkillsError) {
      if (asJson) out(JSON.stringify({ code: error.code, message: error.message }, null, 2))
      else process.stderr.write(`bmn: ${error.code}: ${error.message}\n`)
      return error.code === 'REVISION_CONFLICT' ? EXIT.REVISION_CONFLICT : 1
    }
    if (error instanceof RosterError) return failWith(error, asJson)
    throw error
  }
}
