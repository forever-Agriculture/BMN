// What the owner's test proved, per app version

/** Every recorded test, oldest first; a line BMN cannot read is skipped, never guessed. */
export function skillsTests() {
  let text
  try {
    text = readFileSync(skillsTestsPath(), 'utf8')
  } catch {
    return []
  }
  const entries = []
  for (const line of text.split('\n')) {
    if (line === '') continue
    try {
      const entry = JSON.parse(line)
      if (entry !== null && typeof entry === 'object' && typeof entry.harness === 'string') entries.push(entry)
    } catch {
      // A torn line proves nothing.
    }
  }
  return entries
}

function record(entry) {
  mkdirSync(dirname(skillsTestsPath()), { recursive: true, mode: 0o700 })
  appendFileSync(skillsTestsPath(), `${JSON.stringify(entry)}\n`, { mode: 0o600 })
  return entry
}

/** The last test of one kind for one app, whatever version it ran against, or null. */
export function lastSkillsTest(harness, kind, tests = skillsTests()) {
  let last = null
  for (const entry of tests) if (entry.harness === harness && entry.kind === kind) last = entry
  return last
}

/**
 * Where an app reads skills, as the owner's test showed on exactly this version; the latest test
 * of that version decides, so a later failure takes an earlier pass away. `location` is the folder
 * BMN installs into, `format` whether the app follows a link there, and `readsSource` whether the
 * app reads the skills source itself, in which case nothing is installed and nothing can be hidden.
 */
export function appSkills(harness, { environment = process.env, version, tests = skillsTests(), source }) {
  const base = { harness, version: version ?? null, supported: false, location: null, format: null, reads_source: false, roots: [] }
  if (SKILL_APPS[harness] === undefined) return { ...base, reason: 'BMN does not know this app' }
  if (typeof version !== 'string') return { ...base, reason: `${APP_NAMES[harness]} is not installed, or its version cannot be read` }
  let last = null
  for (const entry of tests) if (entry.harness === harness && entry.kind === 'capability' && entry.version === version) last = entry
  if (last === null) return { ...base, reason: `no test has run on ${APP_NAMES[harness]} ${version}` }
  if (last.outcome !== 'pass' || !Array.isArray(last.roots)) return { ...base, reason: `the test on ${APP_NAMES[harness]} ${version} did not pass: ${last.detail ?? last.outcome}` }
  const found = SKILL_APPS[harness].roots.map((root) => last.roots.find((entry) => entry.root === root)).filter((entry) => entry && (entry.folder === true || entry.link === true))
  if (found.length === 0) return { ...base, reason: `${APP_NAMES[harness]} ${version} showed no skills folder` }
  const sourceReal = real(source)
  const reads = found.some((entry) => real(rootPath(entry.root, environment)) === sourceReal)
  const own = found.find((entry) => real(rootPath(entry.root, environment)) !== sourceReal)
  return {
    ...base, supported: true, reads_source: reads, roots: found.map((entry) => entry.root),
    location: own === undefined ? null : rootPath(own.root, environment), format: own === undefined ? null : own.link === true ? 'link' : 'copy'
  }
}

