/** The folder the skills come from: the approved team file's, or `~/.claude/skills`. */
export function skillsSource(data, environment = process.env) {
  return data?.skills_source ?? `${home(environment)}/.claude/skills`
}

/** The first line of a skill's description, from the front matter of its SKILL.md. */
export function skillDescription(text) {
  const front = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text)
  if (front === null) return ''
  const line = /^description:[ \t]*(.*)$/m.exec(front[1])
  if (line === null) return ''
  let value = line[1].trim()
  if (/^[>|][+-]?$/.test(value)) value = (front[1].slice(line.index + line[0].length).split(/\r?\n/).find((next) => next.trim() !== '') ?? '').trim()
  return value.replace(/^(["'])(.*)\1$/, '$2').slice(0, 200)
}

/**
 * The skills in the source: each folder, or link to a folder, that holds a SKILL.md. A skill BMN
 * cannot read, or whose name an app could not take, is listed as unreadable rather than left out.
 */
export function sourceSkills(source) {
  let names
  try {
    names = readdirSync(source).sort()
  } catch (error) {
    return { path: source, readable: false, detail: error.code === 'ENOENT' ? 'the folder does not exist' : `the folder cannot be read (${error.code ?? 'error'})`, skills: [] }
  }
  const skills = []
  for (const name of names) {
    const path = `${source}/${name}`
    let text
    try {
      text = readFileSync(`${path}/SKILL.md`, 'utf8')
    } catch (error) {
      // Not a skill at all, unless the entry is there and only its SKILL.md is out of reach.
      if (error.code !== 'ENOENT' && error.code !== 'ENOTDIR') skills.push({ name, path, readable: false, detail: `SKILL.md cannot be read (${error.code ?? 'error'})` })
      continue
    }
    if (!SKILL_PATTERN.test(name)) {
      skills.push({ name, path, readable: false, detail: 'the name must be lowercase letters, digits and hyphens' })
      continue
    }
    try {
      skills.push({ name, path, readable: true, description: skillDescription(text), hash: treeHash(real(path)) })
    } catch (error) {
      skills.push({ name, path, readable: false, detail: error instanceof SkillsError ? error.message : `the skill cannot be read (${error.code ?? 'error'})` })
    }
  }
  return { path: source, readable: true, skills }
}

function marksOf(data) {
  return new Map((data?.skills ?? []).map((entry) => [entry.id, entry]))
}

/** Whether an app may have a skill: the skill's own scope, and the public list on a public-only route. */
export function eligible(mark, harness, kind) {
  if (mark?.only !== undefined && !mark.only.includes(harness)) return false
  return kind === 'full' || mark?.public === true
}

