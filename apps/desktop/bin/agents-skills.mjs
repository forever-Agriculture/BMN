// Check

function written() {
  try {
    const value = JSON.parse(readFileSync(writtenPath(), 'utf8'))
    return value !== null && typeof value === 'object' && !Array.isArray(value) ? value : {}
  } catch (error) {
    if (error.code === 'ENOENT') return {}
    throw new RosterError('STATE_CORRUPT', `${writtenPath()} cannot be read`)
  }
}

/** The SKILL.md of a generated copy: BMN's line after the front matter, where every app still reads the skill. */
export function withHeader(text, name, sourceHash) {
  const header = `${HEADER_OPEN} (skill ${name}, sha256 ${sourceHash}). Change the skill there, then run: bmn skills install -->`
  const front = /^---\r?\n[\s\S]*?\r?\n---(?:\r?\n|$)/.exec(text)
  if (front === null) return `${header}\n\n${text}`
  return `${text.slice(0, front[0].length)}${front[0].endsWith('\n') ? '' : '\n'}\n${header}\n${text.slice(front[0].length)}`
}

/** The hash a generated copy of a skill has: the source's entries with SKILL.md carrying BMN's line. */
function generatedHash(skill) {
  const root = real(skill.path)
  const text = withHeader(readFileSync(`${root}/SKILL.md`, 'utf8'), skill.name, skill.hash)
  return sha256(canonicalJson(treeEntries(root).map((entry) => (entry.path === 'SKILL.md' ? { path: 'SKILL.md', kind: 'file', mode: entry.kind === 'file' ? entry.mode : 0o644, hash: sha256(text) } : entry))))
}

/** One state for one skill in one app's folder, by precedence (60.11 AC2); `prior` is what the path holds. */
function installedState(app, skill, records, wanted) {
  const path = `${app.location}/${skill.name}`
  let entry
  try {
    entry = entryOf(path)
  } catch (error) {
    return { state: wanted ? 'unreadable' : 'exposed', path, detail: error.message }
  }
  if (!wanted) return entry.kind === 'missing' ? { state: 'excluded', path } : { state: 'exposed', path, entry, managed: records[path] !== undefined }
  if (entry.kind === 'missing') return { state: 'missing', path, entry }
  const known = records[path]
  if (entry.kind === 'link') {
    const pointsAtSource = entry.target === skill.path || real(path) === real(skill.path)
    if (!pointsAtSource) return { state: 'link', path, entry, link_target: entry.target }
    if (known === undefined) return { state: 'unmanaged', path, entry, link_target: entry.target }
    if (known.kind !== 'link' || known.target !== entry.target) return { state: 'edited-outside', path, entry, link_target: entry.target }
    return { state: app.format === 'link' ? 'current' : 'stale', path, entry }
  }
  if (known === undefined || known.kind !== 'copy') return { state: 'unmanaged', path, entry }
  if (known.hash !== entry.hash) return { state: 'edited-outside', path, entry }
  return { state: app.format === 'copy' && known.source_hash === skill.hash ? 'current' : 'stale', path, entry }
}

/**
 * One row per app and per skill (60.11 AC2). `versions` maps each app to its installed version;
 * `generation` is the approved team, which alone decides the source, the marks and each app's
 * destination. An app without a passed test is `supported: false` and none of its skills is judged.
 */
export function checkSkills({ environment = process.env, tests = skillsTests(), versions, generation = approvedIfAny(), descriptions = false } = {}) {
  const data = generation?.data ?? null
  const marks = marksOf(data)
  const source = sourceSkills(skillsSource(data, environment))
  const records = written()
  const known = new Set(source.skills.map((skill) => skill.name))
  const apps = HARNESSES.map((harness) => {
    const answer = harnessPrivateWork(data, harness)
    const kind = answer.allowed ? 'full' : 'public'
    const app = { ...appSkills(harness, { environment, version: versions?.[harness] ?? null, tests, source: source.path }), kind, kind_reason: answer.reason }
    if (!app.supported || !source.readable) return { ...app, skills: [] }
    const rows = source.skills.map((skill) => {
      if (!skill.readable) return { name: skill.name, state: 'unreadable', detail: skill.detail }
      const wanted = eligible(marks.get(skill.name), harness, kind)
      if (app.reads_source) return { name: skill.name, state: wanted ? 'read-directly' : 'exposed', path: skill.path, direct: true }
      // What the path holds is the plan's business; the row carries the state and where.
      return { name: skill.name, ...Object.fromEntries(Object.entries(installedState(app, skill, records, wanted)).filter(([key]) => key !== 'entry')) }
    })
    // A skill that left the source keeps its tracked entry, shown stale, until its removal is confirmed.
    for (const [path, entry] of Object.entries(records)) {
      if (entry.harness !== harness || known.has(entry.skill)) continue
      let gone
      try {
        gone = entryOf(path).kind === 'missing'
      } catch {
        gone = false
      }
      if (!gone) rows.push({ name: entry.skill, state: 'stale', path, removed: true })
    }
    return { ...app, skills: rows }
  })
  return {
    source: { path: source.path, readable: source.readable, ...(source.detail ? { detail: source.detail } : {}) },
    skills: source.skills.map((skill) => ({ name: skill.name, readable: skill.readable, ...(skill.readable ? { hash: skill.hash } : { detail: skill.detail }),
      ...(descriptions ? { description: skill.description ?? '' } : {}),
      public: marks.get(skill.name)?.public === true, only: marks.get(skill.name)?.only ?? null })),
    marked_missing: [...marks.keys()].filter((name) => !known.has(name)),
    apps
  }
}

/** 0 only when some app is supported, the source is readable and every skill in every supported app is settled. */
export function checkExit(result) {
  const supported = result.apps.filter((app) => app.supported)
  if (!result.source.readable || supported.length === 0) return 1
  return supported.every((app) => app.skills.every((skill) => SETTLED_STATES.includes(skill.state))) ? 0 : 1
}

/** How many entries an install would add, replace or remove, and how many skills stay exposed whatever is installed. */
export function pendingCounts(result) {
  let pending = 0
  let exposed = 0
  for (const app of result.apps) {
    for (const row of app.skills) {
      if (row.state === 'exposed') {
        if (row.managed === true && row.direct !== true) pending += 1
        else exposed += 1
      } else if (!SETTLED_STATES.includes(row.state) && row.state !== 'unreadable') pending += 1
    }
  }
  return { pending, exposed }
}

/** An app's skills in a few words, for Health and for the check's summary line. */
export function appStateWord(app, sourceReadable = true) {
  if (!app.supported) return 'Not supported yet'
  if (!sourceReadable) return 'Differs'
  const states = new Set(app.skills.map((skill) => skill.state))
  if (states.has('exposed')) return 'Exposed'
  if ([...states].some((state) => !SETTLED_STATES.includes(state) && state !== 'missing')) return 'Differs'
  if (states.has('missing')) return 'Missing'
  return app.reads_source ? 'Reads the source' : app.format === 'copy' ? 'Copied' : 'Linked'
}

