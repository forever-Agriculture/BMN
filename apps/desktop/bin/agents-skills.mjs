/**
 * The owner keeps his skills in one folder (`~/.claude/skills/` unless the approved team file names
 * another): one folder or link per skill, each with a `SKILL.md`. BMN gives every agent app the
 * skills it may have: a link to the source entry where the app follows links, or a generated copy
 * where it does not. Nothing is written for an app until the owner's test showed, on exactly the
 * installed version, which folders that app reads skills from (60.11 AC1); until then its skills
 * are "not supported yet".
 *
 * Which skills an app may have: a skill kept to some apps (`only`) reaches only those, and an app
 * whose approved destination is public-only, unknown or the owner's word gets only the skills
 * marked `public`. A skill an app can see but may not have is `exposed`, which no install hides.
 *
 * BMN never prints or stores a skill's text outside its own private state: a plan names files,
 * never their lines.
 */

export class SkillsError extends Error {
  constructor(code, message) {
    super(message)
    this.code = code
  }
}

/**
 * Per app: its program, the folders (under the home folder) it may read user-level skills from,
 * in the order BMN prefers to install into, and the command that lists the skills it sees
 * without sending a prompt. Cursor has no such command, so its skills stay "not supported yet".
 * `prompt` says whether BMN can tell, in a run of that app, the app handing a skill's text to the
 * model from the model reading the file itself; only there does a loading test say pass or fail.
 * These are what BMN asks; what an app answers is recorded by the owner's test, per version.
 */
export const SKILL_APPS = {
  claude: { command: 'claude', roots: ['.claude/skills'], list: { argv: ['-p', '--output-format', 'stream-json', '--verbose', '--no-session-persistence'], input: '/context\n' }, prompt: true },
  codex: { command: 'codex', roots: ['.agents/skills', '.codex/skills', '.claude/skills'], list: { argv: ['debug', 'prompt-input'], input: '' }, prompt: true },
  opencode: { command: 'opencode', roots: ['.config/opencode/skills', '.config/opencode/skill', '.agents/skills', '.claude/skills'], list: { argv: ['debug', 'skill'], input: '' }, prompt: false },
  cursor: { command: 'cursor-agent', roots: ['.cursor/skills', '.agents/skills', '.claude/skills', '.codex/skills'], list: null, prompt: false }
}

/** States that need nothing done: the skill is where it should be, or is rightly absent. */
export const SETTLED_STATES = ['current', 'read-directly', 'excluded']
const TREE_LIMIT = 4000
const HEADER_OPEN = '<!-- Generated by BMN from the skills folder'

function home(environment) {
  return environment.HOME || homedir()
}

/** Where one of an app's folders is on this machine, honouring the variables that move it. */
export function rootPath(root, environment = process.env) {
  const base = home(environment)
  if (root.startsWith('.claude/')) return `${environment.CLAUDE_CONFIG_DIR || `${base}/.claude`}/${root.slice('.claude/'.length)}`
  if (root.startsWith('.codex/')) return `${environment.CODEX_HOME || `${base}/.codex`}/${root.slice('.codex/'.length)}`
  if (root.startsWith('.config/')) return `${environment.XDG_CONFIG_HOME || `${base}/.config`}/${root.slice('.config/'.length)}`
  return `${base}/${root}`
}

export function skillsTestsPath() {
  return `${agentsDirectory()}/state/skills-tests.jsonl`
}

function writtenPath() {
  return `${agentsDirectory()}/state/rules/skills-written.json`
}

function real(path) {
  try {
    return realpathSync(path)
  } catch {
    return path
  }
}

