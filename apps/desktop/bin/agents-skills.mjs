// Install and undo

function fileNames(root) {
  return new Map(treeEntries(root).filter((entry) => entry.kind !== 'folder').map((entry) => [entry.path, entry.kind === 'file' ? entry.hash : `link ${entry.target}`]))
}

/** How a folder BMN did not write differs from the skill, by file name only: a skill's lines are never printed. */
function folderDifference(path, skill) {
  let mine
  let theirs
  try {
    mine = fileNames(path)
    theirs = fileNames(real(skill.path))
  } catch {
    return 'its files cannot be compared'
  }
  const differing = [...mine.keys()].filter((name) => theirs.has(name) && theirs.get(name) !== mine.get(name))
  const onlyHere = [...mine.keys()].filter((name) => !theirs.has(name))
  const onlySource = [...theirs.keys()].filter((name) => !mine.has(name))
  const parts = [
    ...(differing.length ? [`differs from the skill in ${differing.join(', ')}`] : []),
    ...(onlyHere.length ? [`holds ${onlyHere.join(', ')}, which the skill does not`] : []),
    ...(onlySource.length ? [`lacks ${onlySource.join(', ')}`] : [])
  ]
  return parts.length === 0 ? 'holds the same files as the skill' : parts.join('; ')
}

const CHANGE_WORDS = {
  missing: 'adds the skill',
  link: 'replaces a link that points somewhere else',
  unmanaged: 'takes over an entry BMN did not write (unmanaged)',
  'edited-outside': 'replaces an entry changed outside BMN',
  stale: 'updates BMN\'s entry'
}

/**
 * What an install would do, without doing it: per app, the entries to link, copy or remove, each
 * with what the path holds now, plus the skills that stay exposed whatever is installed, and one
 * hash of all of it that a confirmed install must match. `harnesses` empty means every supported app.
 */
export async function planSkillsInstall(harnesses = [], { environment = process.env, versions, tests = skillsTests() } = {}) {
  const generation = approvedIfAny()
  const { routeFor, routeStillMatches } = await import('./agents-rules.mjs')
  const check = checkSkills({ environment, tests, versions, generation })
  if (!check.source.readable) return { code: 'SOURCE_UNREADABLE', message: `${check.source.path}: ${check.source.detail}; nothing was written`, targets: [], exposed: [], planHash: null }
  const named = harnesses.length > 0 ? harnesses : check.apps.filter((app) => app.supported).map((app) => app.harness)
  if (named.length === 0) return { code: 'SKILLS_UNSUPPORTED', message: 'skills are not supported yet in any app: run the test first (Preferences > Rules > Health, or bmn skills test <app>); nothing was written', targets: [], exposed: [], planHash: null }
  const source = sourceSkills(check.source.path)
  const byName = new Map(source.skills.map((skill) => [skill.name, skill]))
  const records = written()
  const targets = []
  const exposed = []
  for (const harness of named) {
    const app = check.apps.find((entry) => entry.harness === harness)
    if (!app.supported) return { code: 'SKILLS_UNSUPPORTED', message: `${APP_NAMES[harness]}: skills not supported yet (${app.reason}); nothing was written`, targets: [], exposed: [], planHash: null }
    // Like the rules: before skills that are not public leave BMN, the app must still send its data where the approved team says.
    const route = await routeStillMatches(harness, routeFor(harness, generation), environment)
    if (!route.ok) return { code: 'ROUTE_CHANGED', message: `${APP_NAMES[harness]} cannot get the full skills: ${route.reason}; ${route.remedy}`, targets: [], exposed: [], planHash: null }
    for (const row of app.skills) {
      if (SETTLED_STATES.includes(row.state) || row.state === 'unreadable') continue
      const base = { harness, skill: row.name, path: row.path }
      if (row.state === 'exposed') {
        if (row.direct === true) {
          exposed.push({ ...base, fix: `${APP_NAMES[harness]} reads the skills folder itself: move ${row.name} out of it, or mark it public` })
        } else if (records[row.path] === undefined) {
          exposed.push({ ...base, fix: `BMN did not write ${row.path}: remove it by hand, or let ${APP_NAMES[harness]} have the skill` })
        } else {
          targets.push({ ...base, action: 'remove', change: 'exposed', words: `removes BMN's entry: ${APP_NAMES[harness]} may no longer have this skill`, prior: entryOf(row.path), wanted: { kind: 'removed' } })
        }
        continue
      }
      if (row.removed === true) {
        targets.push({ ...base, action: 'remove', change: 'stale', words: 'removes BMN\'s entry: the skill left the skills folder', prior: entryOf(row.path), wanted: { kind: 'removed' } })
        continue
      }
      const skill = byName.get(row.name)
      const prior = entryOf(row.path)
      const wanted = app.format === 'link' ? { kind: 'link', target: skill.path } : { kind: 'copy', hash: generatedHash(skill), source_hash: skill.hash }
      const detail = prior.kind === 'link' ? `link to ${prior.target}; the link is replaced, what it points at is not touched`
        : prior.kind === 'tree' && (row.state === 'unmanaged' || row.state === 'edited-outside') ? `the ${prior.folder ? 'folder' : 'file'} there ${folderDifference(row.path, skill)}` : ''
      targets.push({ ...base, action: app.format, change: row.state, words: CHANGE_WORDS[row.state], detail, prior, wanted })
    }
  }
  for (const target of targets) target.resolved = `${target.prior.directory}/${basename(target.path)}`
  return { code: 'OK', source: check.source.path, targets, exposed, planHash: skillsPlanHash(targets) }
}

function skillsPlanHash(targets) {
  return sha256(canonicalJson(targets.map((target) => ({ harness: target.harness, skill: target.skill, path: target.path, action: target.action, prior: target.prior, wanted: target.wanted }))))
}

/** The plan as the panel and `--plan --json` show it. */
export function skillsPlanView(result) {
  return {
    code: result.code, ...(result.message ? { message: result.message } : {}), plan_hash: result.planHash, source: result.source ?? null,
    targets: result.targets.map((target) => ({ harness: target.harness, skill: target.skill, path: target.path, resolved_path: target.resolved, action: target.action, change: target.change,
      words: target.words, ...(target.detail ? { detail: target.detail } : {}), ...(target.prior.kind === 'link' ? { link_target: target.prior.target } : {}) })),
    exposed: result.exposed
  }
}

function planDetails(planned) {
  const lines = planned.targets.map((target) => [
    `${target.harness}: ${target.path}${target.resolved === target.path ? '' : ` (written at ${target.resolved})`}`,
    `  ${target.words}${target.action === 'link' ? `; becomes a link to ${target.wanted.target}` : target.action === 'copy' ? '; becomes a copy with BMN\'s line in SKILL.md' : ''}`,
    ...(target.detail ? [`  ${target.detail}`] : [])
  ].join('\n'))
  const open = planned.exposed.map((entry) => `still exposed: ${entry.harness} ${entry.skill} - ${entry.fix}`)
  return [...lines, ...open].join('\n')
}

function stagePath(path) {
  return `${dirname(path)}/.${basename(path)}.bmn-${process.pid}-${Date.now()}-${randomBytes(3).toString('hex')}.tmp`
}

/**
 * Puts a staged entry in a path's place. A link or file over a link or file is one rename; where a
 * folder is involved the old entry is moved aside first, since no rename replaces one, and moved
 * back if the new one cannot take its place. Only the entry itself moves: a link is never followed.
 */
function swapIn(staged, path, prior) {
  const stagedIsFolder = lstatSync(staged).isDirectory()
  if (prior.kind === 'missing' || (!stagedIsFolder && !(prior.kind === 'tree' && prior.folder))) {
    renameSync(staged, path)
    return
  }
  const aside = stagePath(path)
  renameSync(path, aside)
  try {
    renameSync(staged, path)
  } catch (error) {
    renameSync(aside, path)
    throw error
  }
  rmSync(aside, { recursive: true, force: true })
}

function unchanged(path, expected) {
  if (!sameEntry(entryOf(path), expected)) throw new SkillsError('REVISION_CONFLICT', `${path} changed while BMN was reading it; nothing was written there`)
}

/** Writes one planned entry and reads it back. */
function writeTarget(target, skill) {
  unchanged(target.path, target.prior)
  if (target.action === 'remove') {
    rmSync(target.path, { recursive: true, force: true })
    if (entryOf(target.path).kind !== 'missing') throw new SkillsError('READBACK_FAILED', `${target.path} is still there; check it by hand`)
    return
  }
  mkdirSync(dirname(target.path), { recursive: true })
  const staged = stagePath(target.path)
  try {
    if (target.action === 'link') {
      symlinkSync(target.wanted.target, staged)
    } else {
      const root = real(skill.path)
      copyTree(root, staged)
      const text = withHeader(readFileSync(`${root}/SKILL.md`, 'utf8'), skill.name, skill.hash)
      // The copy's SKILL.md is always its own regular file: where the skill's is a link, writing through it would change what it points at.
      const mode = lstatSync(`${root}/SKILL.md`).isFile() ? lstatSync(`${root}/SKILL.md`).mode & 0o777 : 0o644
      rmSync(`${staged}/SKILL.md`, { force: true })
      writeFileSync(`${staged}/SKILL.md`, text, { mode, flag: 'wx' })
      chmodSync(`${staged}/SKILL.md`, mode)
      if (treeHash(staged) !== target.wanted.hash) throw new SkillsError('REVISION_CONFLICT', `${skill.path} changed while BMN was copying it; nothing was written there`)
    }
    unchanged(target.path, target.prior)
    swapIn(staged, target.path, target.prior)
  } catch (error) {
    rmSync(staged, { recursive: true, force: true })
    throw error
  }
  const after = entryOf(target.path)
  const good = target.action === 'link' ? after.kind === 'link' && after.target === target.wanted.target : after.kind === 'tree' && after.hash === target.wanted.hash
  if (!good) throw new SkillsError('READBACK_FAILED', `${target.path} does not hold what BMN wrote; check it by hand`)
}

function recordOf(target) {
  return target.action === 'link' ? { harness: target.harness, skill: target.skill, kind: 'link', target: target.wanted.target }
    : { harness: target.harness, skill: target.skill, kind: 'copy', hash: target.wanted.hash, source_hash: target.wanted.source_hash }
}

/**
 * One install transaction (60.11 AC3): show every entry, ask (default No), plan again and write
 * only what was confirmed. Each entry's prior state is kept first: a link as its text, a folder as
 * a complete private copy with its modes and its own links kept as links. A failure part-way stops
 * and keeps the manifest, so `bmn rules restore --transaction` can undo what changed.
 */
export async function installSkills(harnesses = [], { yes = false, asJson = false, environment = process.env, versions, now = new Date(), expectedPlanHash, afterConfirm, beforeTarget, afterTarget } = {}) {
  const { confirm } = await import('./agents-rules.mjs')
  const planned = await planSkillsInstall(harnesses, { environment, versions })
  if (planned.code !== 'OK') return { code: planned.code, message: planned.message, transaction: null, written: [], exposed: [] }
  if (expectedPlanHash !== undefined && expectedPlanHash !== planned.planHash) {
    return { code: 'REVISION_CONFLICT', message: 'the skills or the folders changed since the plan was shown; review it again', transaction: null, written: [], exposed: planned.exposed }
  }
  if (planned.targets.length === 0) {
    return { code: 'OK', transaction: null, written: [], exposed: planned.exposed, message: planned.exposed.length > 0 ? 'Nothing to install; some skills stay exposed.' : 'Every app already has its skills.' }
  }
  if (!await confirm('Change these skills entries?', planDetails(planned), { yes, asJson })) return { code: 'NOT_CONFIRMED', transaction: null, written: [], exposed: planned.exposed }
  // The answer may come long after the list: plan again and write only what was confirmed.
  afterConfirm?.()
  const confirmed = await planSkillsInstall(harnesses, { environment, versions })
  if (confirmed.code !== 'OK') return { code: confirmed.code, message: confirmed.message, transaction: null, written: [], exposed: [] }
  if (confirmed.planHash !== planned.planHash) {
    return { code: 'REVISION_CONFLICT', message: 'the skills or the folders changed while the confirmation was open; nothing was written', transaction: null, written: [], exposed: confirmed.exposed }
  }
  return writeSkillsTransaction(confirmed, { now, beforeTarget, afterTarget })
}

async function writeSkillsTransaction(planned, { now, beforeTarget, afterTarget }) {
  const { newTransaction, writePrivate } = await import('./agents-rules.mjs')
  const { id, folder } = newTransaction(now)
  const records = written()
  const byName = new Map(sourceSkills(planned.source).skills.map((skill) => [skill.name, skill]))
  const manifest = {
    id, created_at: now.toISOString(), kind: 'skills', reason: 'skills install', state: 'started', source: planned.source,
    targets: planned.targets.map((target, index) => ({
      harness: target.harness, skill: target.skill, path: target.path, action: target.action,
      prior: target.prior.kind === 'tree' ? { kind: 'tree', backup: `${index}.tree`, hash: target.prior.hash } : { kind: target.prior.kind, ...(target.prior.kind === 'link' ? { target: target.prior.target } : {}) },
      // `written` is what the entry will hold; `started` is set, and kept on disk, before the entry is touched.
      prior_record: records[target.path] ?? null, written: target.wanted, started: false, done: false
    }))
  }
  const save = () => writePrivate(`${folder}/manifest.json`, JSON.stringify(manifest, null, 2))
  planned.targets.forEach((target, index) => {
    if (target.prior.kind === 'tree') copyTree(target.path, `${folder}/${index}.tree`)
  })
  save()
  const done = []
  for (const [index, target] of planned.targets.entries()) {
    try {
      beforeTarget?.(target, index)
      manifest.targets[index].started = true
      save()
      writeTarget(target, byName.get(target.skill))
      afterTarget?.(target, index)
    } catch (error) {
      manifest.state = 'failed'
      save()
      return { code: 'INSTALL_FAILED', transaction: id, written: done, exposed: planned.exposed,
        message: `${target.path}: ${error.code ?? 'write failed'}: ${error.message}; ${done.length} entr${done.length === 1 ? 'y' : 'ies'} changed; undo with bmn rules restore --transaction ${id}` }
    }
    const next = written()
    if (target.action === 'remove') delete next[target.path]
    else next[target.path] = recordOf(target)
    writePrivate(writtenPath(), JSON.stringify(next, null, 2))
    manifest.targets[index].done = true
    save()
    done.push({ harness: target.harness, skill: target.skill, path: target.path, action: target.action })
  }
  manifest.state = 'complete'
  save()
  return { code: 'OK', transaction: id, written: done, exposed: planned.exposed }
}

/** Whether an entry holds exactly what an install meant to leave there. */
function holdsWritten(current, wanted) {
  if (wanted?.kind === 'link') return current.kind === 'link' && current.target === wanted.target
  if (wanted?.kind === 'copy') return current.kind === 'tree' && current.hash === wanted.hash
  return wanted?.kind === 'removed' && current.kind === 'missing'
}

/**
 * Undoes one skills transaction (called by `bmn rules restore --transaction`): every entry it
 * changed goes back to what it was, a link as a link and a folder from its private copy, and BMN's
 * records with it. Shown and confirmed like the install. An entry is put back only while it still
 * holds exactly what the install left there (the link it made, the copy with that content and
 * those modes, or nothing where it removed one): one changed since is the owner's, stops the
 * restore there and stays. An entry the install changed without getting to record it as done is
 * undone too, known the same way; one it never began, or began and did not change, is left out.
 */
export async function restoreSkillsTransaction(manifest, folder, { yes = false, asJson = false, planOnly = false, expectedPlanHash } = {}) {
  const { confirm, writePrivate } = await import('./agents-rules.mjs')
  const plans = manifest.targets.map((target) => ({ ...target, current: entryOf(target.path) })).filter((plan) => {
    if (plan.done === true) return true
    if (plan.started !== true) return false
    const asBefore = plan.current.kind === (plan.prior.kind === 'tree' ? 'tree' : plan.prior.kind) && plan.current.target === plan.prior.target && plan.current.hash === plan.prior.hash
    return !asBefore
  })
  const becomes = (prior) => (prior.kind === 'link' ? `link to ${prior.target}` : prior.kind === 'missing' ? 'removed (it did not exist)' : 'the folder as it was')
  const targets = plans.map((plan) => ({ harness: plan.harness, skill: plan.skill, path: plan.path, resolved_path: `${plan.current.directory}/${basename(plan.path)}`, change: plan.prior.kind === 'tree' ? 'folder' : plan.prior.kind, becomes: becomes(plan.prior), diff: '', note: 'A skill is put back whole; its lines are not shown.' }))
  const hash = sha256(canonicalJson(plans.map((plan) => ({ path: plan.path, current: plan.current, prior: plan.prior }))))
  if (planOnly) return { code: 'OK', plan_hash: hash, targets }
  if (expectedPlanHash !== undefined && expectedPlanHash !== hash) return { code: 'REVISION_CONFLICT', message: 'the entries changed since the restore was shown; review it again' }
  const details = targets.map((target) => `${target.harness}: ${target.path}${target.resolved_path === target.path ? '' : ` (written at ${target.resolved_path})`} -> ${target.becomes}`).join('\n')
  if (!await confirm(`Restore transaction ${manifest.id}?`, details, { yes, asJson })) return { code: 'NOT_CONFIRMED' }
  const restored = []
  for (const plan of plans) {
    if (!sameEntry(entryOf(plan.path), plan.current)) {
      return { code: 'REVISION_CONFLICT', message: `${plan.path} changed while BMN was reading it; ${restored.length} entr${restored.length === 1 ? 'y' : 'ies'} restored`, restored }
    }
    if (!holdsWritten(plan.current, plan.written)) {
      return { code: 'REVISION_CONFLICT', message: `${plan.path} changed since BMN wrote it; ${restored.length} entr${restored.length === 1 ? 'y' : 'ies'} restored`, restored }
    }
    if (plan.prior.kind === 'missing') {
      rmSync(plan.path, { recursive: true, force: true })
    } else {
      mkdirSync(dirname(plan.path), { recursive: true })
      const staged = stagePath(plan.path)
      try {
        if (plan.prior.kind === 'link') symlinkSync(plan.prior.target, staged)
        else copyTree(`${folder}/${plan.prior.backup}`, staged)
        if (plan.current.kind === 'missing') renameSync(staged, plan.path)
        else swapIn(staged, plan.path, plan.current)
      } catch (error) {
        rmSync(staged, { recursive: true, force: true })
        throw error
      }
    }
    const records = written()
    if (plan.prior_record === null) delete records[plan.path]
    else records[plan.path] = plan.prior_record
    writePrivate(writtenPath(), JSON.stringify(records, null, 2))
    restored.push(plan.harness)
  }
  return { code: 'OK', kind: 'skills', restored: [...new Set(restored)] }
}

