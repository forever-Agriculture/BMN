/**
 * Every entry of a folder, in name order, without following a link: a file with its mode and the
 * hash of its bytes, a link with its text, a folder with its mode. This is what a copy must
 * reproduce and what a backup must put back.
 */
export function treeEntries(root) {
  const entries = []
  const walk = (path, relative) => {
    if (entries.length >= TREE_LIMIT) throw new SkillsError('TOO_LARGE', `${root} holds more than ${TREE_LIMIT} entries`)
    const stat = lstatSync(path)
    if (stat.isSymbolicLink()) {
      entries.push({ path: relative, kind: 'link', target: readlinkSync(path) })
    } else if (stat.isDirectory()) {
      entries.push({ path: relative, kind: 'folder', mode: stat.mode & 0o777 })
      for (const name of readdirSync(path).sort()) walk(`${path}/${name}`, relative === '' ? name : `${relative}/${name}`)
    } else if (stat.isFile()) {
      entries.push({ path: relative, kind: 'file', mode: stat.mode & 0o777, hash: sha256(readFileSync(path)) })
    } else {
      entries.push({ path: relative, kind: 'other' })
    }
  }
  walk(root, '')
  return entries
}

export function treeHash(root) {
  return sha256(canonicalJson(treeEntries(root)))
}

/** A copy that keeps modes and keeps every link as a link; what a link points at is never read. */
export function copyTree(from, to) {
  const stat = lstatSync(from)
  if (stat.isSymbolicLink()) {
    symlinkSync(readlinkSync(from), to)
  } else if (stat.isDirectory()) {
    mkdirSync(to, { mode: 0o700 })
    for (const name of readdirSync(from)) copyTree(`${from}/${name}`, `${to}/${name}`)
    chmodSync(to, stat.mode & 0o777)
  } else if (stat.isFile()) {
    copyFileSync(from, to)
    chmodSync(to, stat.mode & 0o777)
  } else {
    throw new SkillsError('NOT_A_FILE', `${from} is not a file, a folder or a link`)
  }
}

/** What a path holds, without following a final link, and the real folder that holds it. */
export function entryOf(path) {
  let directory
  try {
    directory = realpathSync(dirname(path))
  } catch {
    directory = linkTarget(dirname(path))
  }
  let stat
  try {
    stat = lstatSync(path)
  } catch (error) {
    if (error.code === 'ENOENT') return { kind: 'missing', directory }
    throw error
  }
  if (stat.isSymbolicLink()) return { kind: 'link', target: readlinkSync(path), directory }
  return { kind: 'tree', hash: treeHash(path), folder: stat.isDirectory(), directory }
}

function sameEntry(a, b) {
  return a.kind === b.kind && a.target === b.target && a.hash === b.hash && a.directory === b.directory
}

