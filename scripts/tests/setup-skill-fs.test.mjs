// MODULE: setup-skill-fs.test.mjs - Descriptor-bound tree/link staging and preservation under independent edits
import assert from 'node:assert/strict'
import { chmodSync, closeSync, existsSync, mkdirSync, mkdtempSync, openSync, readFileSync, readlinkSync, renameSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { basename, join } from 'node:path'
import { afterEach, beforeEach, describe, it } from 'vitest'
import { withDefaultsAdmission } from '../../apps/desktop/bin/defaults-admission.mjs'
import { treeHash } from '../../apps/desktop/bin/agents-skills.mjs'
import { newTransaction } from '../../apps/desktop/bin/agents-rules.mjs'
import { setupFileParent, setupPinnedPath } from '../../apps/desktop/bin/setup-file-defaults.mjs'
import { holdSetupSkill, observeSetupSkill, stageSetupSkill } from '../../apps/desktop/bin/setup-skill-fs.mjs'

let root, home, parent, path, manifest, folder
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'bmn-setup-skill-fs-')); home = process.env.HOME; process.env.HOME = root
  mkdirSync(join(root, 'skills')); path = join(root, 'skills/plan'); parent = setupFileParent(path)
  withDefaultsAdmission(() => { const allocated = newTransaction(new Date()); folder = allocated.folder; manifest = { id: allocated.id, kind: 'setup-skill', setup: {} } })
})
afterEach(() => { closeSync(parent.fd); if (home === undefined) delete process.env.HOME; else process.env.HOME = home; rmSync(root, { recursive: true, force: true }) })
const admitted = work => withDefaultsAdmission(work, { directory: root })
function source() {
  const source = join(root, 'shipped/plan'); mkdirSync(source, { recursive: true, mode: 0o750 })
  writeFileSync(join(source, 'SKILL.md'), '---\nname: plan\n---\nSynthetic skill\n', { mode: 0o640 })
  writeFileSync(join(source, 'script'), 'synthetic script', { mode: 0o750 }); symlinkSync('script', join(source, 'alias'))
  return source
}

describe('setup skill filesystem boundary', () => {
  it('stages an exact tree including modes and link text without following its links', () => admitted(() => {
    const from = source(), staged = stageSetupSkill(parent, { kind: 'tree', source: from }, manifest.id)
    assert.equal(staged.fingerprint.hash, treeHash(from))
    assert.equal(readlinkSync(setupPinnedPath(parent, `${staged.name}/alias`)), 'script')
    assert.deepEqual(staged.links.map(link => [link.path, link.text]), [['alias', 'script']])
    assert.equal(observeSetupSkill(join(parent.real, staged.name), parent).hash, staged.fingerprint.hash)
  }))

  it('makes a generated copy with a regular SKILL.md and the same hash contract as the legacy generator', () => admitted(() => {
    const from = source(), staged = stageSetupSkill(parent, { kind: 'tree', source: from, header: { name: 'plan', sourceHash: treeHash(from) } }, manifest.id)
    const text = readFileSync(join(parent.real, staged.name, 'SKILL.md'), 'utf8')
    assert(text.startsWith('---\nname: plan\n---\n\n<!-- Generated by BMN'))
    assert.equal(staged.fingerprint.hash, treeHash(join(parent.real, staged.name)))
  }))

  it('refuses a generated copy whose SKILL.md is a link instead of silently omitting its provenance header', () => admitted(() => {
    const from = source(); rmSync(join(from, 'SKILL.md')); symlinkSync('script', join(from, 'SKILL.md'))
    assert.throws(() => stageSetupSkill(parent, { kind: 'tree', source: from,
      header: { name: 'plan', sourceHash: treeHash(from) } }, manifest.id), { code: 'REVISION_CONFLICT' })
    assert.equal(readlinkSync(join(from, 'SKILL.md')), 'script')
  }))

  for (const kind of ['tree', 'link']) it(`preserves a removed ${kind} instead of unlinking it`, () => admitted(() => {
    if (kind === 'tree') { mkdirSync(path); writeFileSync(join(path, 'SKILL.md'), 'synthetic') }
    else symlinkSync(join(root, 'backing/plan'), path)
    const expected = observeSetupSkill(path, parent)
    const held = holdSetupSkill(path, expected, parent, { manifest, folder })
    assert.equal(observeSetupSkill(path, parent).kind, 'absent')
    assert.deepEqual(observeSetupSkill(held.holdingPath, parent), expected)
    assert.equal(held.phase, 'verified')
    assert.throws(() => holdSetupSkill(path, expected, parent, { manifest, folder }), /inspection/)
  }))

  for (const change of ['same-byte-replacement', 'child-mode', 'child-link', 'child-in-place']) it(`refuses ${change} after quarantine and preserves the foreign object`, () => admitted(() => {
    mkdirSync(path); writeFileSync(join(path, 'SKILL.md'), 'synthetic'); symlinkSync('SKILL.md', join(path, 'alias'))
    const expected = observeSetupSkill(path, parent)
    const fd = change === 'child-in-place' ? openSync(join(path, 'SKILL.md'), 'r+') : null
    let heldPath
    try {
      assert.throws(() => holdSetupSkill(path, expected, parent, { manifest, folder, afterMove: ({ holdingPath }) => {
        heldPath = holdingPath
        if (change === 'same-byte-replacement') {
          renameSync(holdingPath, `${holdingPath}-original`); mkdirSync(holdingPath); writeFileSync(join(holdingPath, 'SKILL.md'), 'synthetic'); symlinkSync('SKILL.md', join(holdingPath, 'alias'))
        } else if (change === 'child-mode') chmodSync(join(holdingPath, 'SKILL.md'), 0o600)
        else if (change === 'child-link') { rmSync(join(holdingPath, 'alias')); symlinkSync('foreign', join(holdingPath, 'alias')) }
        else writeFileSync(fd, 'foreign mutation')
        writeFileSync(path, 'foreign occupying original name', { flag: 'wx' })
      } }), error => { assert.equal(error.code, 'REVISION_CONFLICT'); assert.match(error.message, /recovery path/); return true })
      assert(existsSync(heldPath)); assert.equal(readFileSync(path, 'utf8'), 'foreign occupying original name')
    } finally { if (fd !== null) closeSync(fd) }
  }))

  it('returns a displaced foreign object only to an absent original name', () => admitted(() => {
    symlinkSync('/synthetic/old', path); const expected = observeSetupSkill(path, parent)
    assert.throws(() => holdSetupSkill(path, expected, parent, { manifest, folder, afterMove: ({ holdingPath }) => {
      rmSync(holdingPath); symlinkSync('/synthetic/foreign', holdingPath)
    } }), { code: 'REVISION_CONFLICT' })
    assert.equal(readlinkSync(path), '/synthetic/foreign')
    assert.equal(manifest.setup.removal.phase, 'foreign-returned')
  }))

  it('refuses an unsafe source root and a changed physical parent before staging', () => admitted(() => {
    const from = source(); symlinkSync(from, join(root, 'source-link'))
    assert.throws(() => stageSetupSkill(parent, { kind: 'tree', source: join(root, 'source-link') }, manifest.id))
    renameSync(join(root, 'skills'), join(root, 'old-skills')); mkdirSync(join(root, 'skills'))
    assert.throws(() => stageSetupSkill(parent, { kind: 'link', text: '/synthetic/target' }, manifest.id), { code: 'REVISION_CONFLICT' })
    assert.equal(existsSync(join(root, 'skills', basename(path))), false)
  }))
})
