// MODULE: desktop-launcher.mjs - the Linux launcher that holds a desktop start until a queued source update finishes
import { homedir } from 'node:os'
import { basename, dirname, join } from 'node:path'

export const UPDATE_UNIT = 'bmn-desktop-update.service'

/** Where the update worker records its phase; the launcher reads it to tell waiting from building. */
export function updateStateDirectory(env = process.env) {
  return join(env.XDG_STATE_HOME || join(homedir(), '.local/state'), 'bmn', 'source-update')
}

export function launcherPath(env = process.env) {
  return join(env.XDG_DATA_HOME || join(homedir(), '.local/share'), 'bmn', 'launch-bmn')
}

/** Where the command stands for sessions outside BMN: the hook's PreToolUse entry looks here for the command guard (Story 102.4). */
export function commandLinkPath(env = process.env) {
  return join(env.HOME || homedir(), '.local/bin/bmn')
}

const COMMAND_LINK_MARK = '# Generated by scripts/install/desktop-entry.mjs: the bmn command for sessions outside BMN.'

/** A small script, not a link: the packaged launcher finds its runtime from its own path. */
export function commandLinkScript(binary) {
  return `#!/bin/sh\n${COMMAND_LINK_MARK}\nexec ${shellQuote(join(dirname(binary), 'resources/bin/bmn'))} "$@"\n`
}

/** Whether BMN may write at that path: nothing there, or what it wrote before; never a command of his. */
export const commandLinkIsOurs = (text) => text === null || text.includes(COMMAND_LINK_MARK)

function shellQuote(value) {
  return `'${value.replaceAll("'", "'\\''")}'`
}

/**
 * A POSIX shell launcher, so a desktop start never depends on the node that built it. While the
 * update unit is active it waits, except when the update is still waiting for a running BMN to exit:
 * then the start is forwarded to that instance, whose single-instance lock focuses it.
 *
 * A held start shows a progress window that names the phase it is waiting on, because a desktop with
 * nothing on it cannot be told apart from a start that failed. The window is informational: nothing
 * it offers stops the update, and dismissing it never starts a half-replaced build.
 *
 * After a failed update it says which build it will open, from the `liveBuild` the worker recorded:
 * the unchanged previous build, the new build that passed its checks, or none when the swap stopped
 * half way - then it opens nothing.
 */
export function launcherScript({ binary, statusPath, unit = UPDATE_UNIT }) {
  const previous = join(`${dirname(binary)}.prev`, basename(binary))
  return `#!/bin/sh
# Generated by scripts/install/desktop-entry.mjs; waits for a queued BMN update before starting BMN.
binary=${shellQuote(binary)}
previous=${shellQuote(previous)}
status=${shellQuote(statusPath)}
unit=${shellQuote(unit)}
log=\${status%.json}.log

updating() {
  systemctl --user is-active --quiet "$unit" 2>/dev/null
}

# BMN's own helpers (its CLI, team-ask supervisors, QA relays) run the binary as Node and may outlive the
# window; only the app counts as running. An unreadable environment counts as the app.
helper() {
  sed -z -n '/^ELECTRON_RUN_AS_NODE=./q 7' "$1/environ" 2>/dev/null
  [ $? -eq 7 ]
}

running() {
  for exe in /proc/[0-9]*/exe; do
    target=$(readlink "$exe" 2>/dev/null) || continue
    [ "\${target% (deleted)}" = "$binary" ] || continue
    helper "\${exe%/exe}" || return 0
  done
  return 1
}

phase() {
  sed -n 's/.*"phase": *"\\([^"]*\\)".*/\\1/p' "$status" 2>/dev/null | tail -n 1
}

live_build() {
  sed -n 's/.*"liveBuild": *"\\([^"]*\\)".*/\\1/p' "$status" 2>/dev/null | tail -n 1
}

# Nothing to open: say why, offer the log, start nothing.
no_build() {
  if command -v zenity >/dev/null 2>&1; then
    zenity --question --title 'BMN update failed' --width 380 --text "$1" \\
      --ok-label 'Show log' --cancel-label 'Close' 2>/dev/null && xdg-open "$log" >/dev/null 2>&1
  else
    notify-send --urgency critical 'BMN update failed' "$1 Log: $log" 2>/dev/null
  fi
  exit 1
}

# The last build step the worker announced, so the window says more than "please wait".
step() {
  sed -n 's/^[^ ]* START \\([^:]*\\):.*/\\1/p' "$log" 2>/dev/null | tail -n 1
}

describe() {
  case $(phase) in
    queued|waiting-for-exit) echo 'Getting the update ready…' ;;
    building)
      case $(step) in
        package) echo 'Packaging the new build. This usually takes 1-3 minutes.' ;;
        'packaged smoke test') echo 'Checking the new build…' ;;
        'desktop install') echo 'Finishing the install…' ;;
        *) echo 'Packaging the new build…' ;;
      esac ;;
    complete) echo 'Update complete. Opening BMN…' ;;
    *) echo 'Updating BMN…' ;;
  esac
}

# Feeds zenity: "#text" retitles the bar, and the closing 100 ends the window when the update does.
feed() {
  last=
  while updating; do
    text=$(describe)
    if [ "$text" != "$last" ]; then
      printf '#%s\\n' "$text"
      last=$text
    fi
    sleep 1
  done
  printf '100\\n'
}

window() {
  feed | zenity --progress --pulsate --auto-close --width 380 \\
    --title 'BMN is updating' --text 'Getting the update ready…' \\
    --cancel-label "Don't wait" 2>/dev/null
}

# BMN update restart v1
# A restart launch must not hand over to the instance that requested it. Bind the wait to
# Linux's process start ticks as well as its PID, so PID reuse never holds a later process.
restart_waited=
case "$BMN_RESTART_WAIT_PID:$BMN_RESTART_WAIT_TICKS" in
  *[!0-9:]*|:*|*:) ;;
  *) restart_waited=yes
     [ "$BMN_RESTART_ACK" = 1 ] && { printf 'READY\\n' >&3; exec 3>&-; }
     restart_left=15
     while [ "$(sed 's/.*) //' "/proc/$BMN_RESTART_WAIT_PID/stat" 2>/dev/null | awk '{print $20}')" = "$BMN_RESTART_WAIT_TICKS" ]; do
       [ -n "$BMN_RESTART_AUTH_PATH" ] && [ "$(cat "$BMN_RESTART_AUTH_PATH" 2>/dev/null)" = "$BMN_RESTART_AUTH_ID revoked" ] && exit 0
       [ "$restart_left" -gt 0 ] || exit 1
       restart_left=$((restart_left - 1))
       sleep 1
     done
     # Authorization is committed only in the main process's final synchronous exit turn.
     # A cancelled or crashed attempt cannot activate on a later ordinary quit.
     if [ -n "$BMN_RESTART_AUTH_PATH" ]; then
       [ "$(cat "$BMN_RESTART_AUTH_PATH" 2>/dev/null)" = "$BMN_RESTART_AUTH_ID launch" ] || exit 0
     fi ;;
esac
unset BMN_RESTART_WAIT_PID BMN_RESTART_WAIT_TICKS BMN_RESTART_ACK BMN_RESTART_AUTH_PATH BMN_RESTART_AUTH_ID

waited=$restart_waited
if updating; then
  case $(phase) in
    queued|waiting-for-exit) [ -z "$restart_waited" ] && running && exec "$binary" "$@" ;;
  esac
  waited=yes
  if command -v zenity >/dev/null 2>&1; then
    window
    # Dismissed, or the window could not be shown: never start a half-replaced build.
    updating && exit 0
  else
    notify-send 'BMN is updating' 'BMN opens when the update finishes.' 2>/dev/null
    while updating; do sleep 1; done
  fi
fi

# Only this run's own wait reports a failure; a stale failed status must not greet every later start.
if [ -n "$waited" ] && [ "$(phase)" = failed ]; then
  case $(live_build) in
    none) no_build 'The update stopped while replacing the build, so there is no build to open. Nothing was started.' ;;
    new) text='The new build passed its checks, but the update did not finish. Open BMN starts the new build.' ;;
    *) text='The update failed its checks. Your previous build is unchanged.' ;;
  esac
  [ -x "$binary" ] || no_build 'The update failed and there is no build to open. Nothing was started.'
  if command -v zenity >/dev/null 2>&1; then
    zenity --question --title 'BMN update failed' --width 380 --text "$text" \\
      --ok-label 'Open BMN' --cancel-label 'Show log' 2>/dev/null || {
      xdg-open "$log" >/dev/null 2>&1
      exit 0
    }
  else
    notify-send --urgency critical 'BMN update failed' "$text Log: $log" 2>/dev/null
  fi
fi

if [ ! -x "$binary" ]; then
  # An update that stopped between its two renames leaves the old build in .prev and none in place.
  [ -x "$previous" ] && no_build "An update stopped while replacing the build; the previous build is in \${previous%/*}. Nothing was started."
  notify-send --urgency critical 'BMN cannot start' "No packaged BMN at $binary" 2>/dev/null
  exit 1
fi
if [ -n "$waited" ]; then
  BMN_UPDATE_RESTART_RESULT=complete
  if [ "$(phase)" = failed ]; then BMN_UPDATE_RESTART_RESULT=$(live_build); fi
  export BMN_UPDATE_RESTART_RESULT
fi
exec "$binary" "$@"
`
}
